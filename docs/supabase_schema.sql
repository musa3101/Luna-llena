END $$;

-- 2. Tabla de Consentimientos de Cookies (RGPD Compliance)
CREATE TABLE IF NOT EXISTS public.cookie_consents (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    visitor_uuid text NOT NULL,
    accepted_essential boolean DEFAULT true,
    accepted_analytics boolean DEFAULT false,
    user_agent text,
    ip_address text,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.cookie_consents ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    DROP POLICY IF EXISTS "Permitir insercion anonima de cookies" ON public.cookie_consents;
    CREATE POLICY "Permitir insercion anonima de cookies" ON public.cookie_consents FOR INSERT WITH CHECK (true);
END $$;

-- 3. Tabla de Contenidos del Sitio (Traducciones y Textos Editables)
CREATE TABLE IF NOT EXISTS public.site_content (
    key text PRIMARY KEY,
    value_es text NOT NULL,
    value_en text NOT NULL,
    category text,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.site_content ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    DROP POLICY IF EXISTS "Permitir lectura publica de contenidos" ON public.site_content;
    CREATE POLICY "Permitir lectura publica de contenidos" ON public.site_content FOR SELECT USING (true);
END $$;

-- 4. Tabla de Platos Destacados (Carta Digital)
CREATE TABLE IF NOT EXISTS public.dishes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key text UNIQUE NOT NULL,
    title_es text NOT NULL,
    title_en text NOT NULL,
    description_es text NOT NULL,
    description_en text NOT NULL,
    image_url text,
    is_active boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.dishes ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    DROP POLICY IF EXISTS "Permitir lectura publica de platos" ON public.dishes;
    CREATE POLICY "Permitir lectura publica de platos" ON public.dishes FOR SELECT USING (true);
END $$;

-- 5. Tabla de Reservas de Mesa (Histórico & Backup)
CREATE TABLE IF NOT EXISTS public.reservations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL,
    phone text NOT NULL,
    guests integer NOT NULL DEFAULT 2,
    reservation_date date NOT NULL,
    reservation_time text NOT NULL,
    allergies text,
    status text DEFAULT 'pending',
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    DROP POLICY IF EXISTS "Permitir insercion publica de reservas" ON public.reservations;
    CREATE POLICY "Permitir insercion publica de reservas" ON public.reservations FOR INSERT WITH CHECK (true);
END $$;

-- 6. Tabla de Pedidos Rápidos (Histórico & Backup)
CREATE TABLE IF NOT EXISTS public.orders (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL,
    surname text,
    phone text NOT NULL,
    categories text[],
    notes text,
    status text DEFAULT 'pending',
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    DROP POLICY IF EXISTS "Permitir insercion publica de pedidos" ON public.orders;
