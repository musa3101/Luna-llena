    locality text DEFAULT 'Palma de Mallorca',
    postal_code text DEFAULT '07013',
    region text DEFAULT 'Illes Balears',
    telephone text DEFAULT '+34631122757',
    whatsapp text DEFAULT '34631122757',
    email text DEFAULT 'barlunallena16@gmail.com',
    hours_weekdays_es text DEFAULT '08:00h - 23:00h',
    hours_sunday_es text DEFAULT 'Cerrado',
    hours_weekdays_en text DEFAULT '08:00h - 23:00h',
