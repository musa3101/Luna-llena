    google_maps_url text DEFAULT 'https://maps.app.goo.gl/Wvg1TphkJxpHRdtUA',
    instagram_url text DEFAULT 'https://www.instagram.com/barlunallena',
    is_open boolean DEFAULT true,
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
